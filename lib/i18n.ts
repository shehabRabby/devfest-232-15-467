export const translations: Record<Language, TranslationDictionary> = { en, bn };

export function formatValidationError(error: ValidationError, language: Language): string {
  return translations[language].validationErrors[error.code]
    .replace("{path}", error.path ?? "")
    .replace("{id}", error.requirementId ?? "");
}

export function formatNumber(value: number, language: Language): string {
  return new Intl.NumberFormat(language === "bn" ? "bn-BD" : "en-US").format(value);
}

export function formatFileSize(bytes: number, language: Language): string {
  const unit = bytes >= 1024 * 1024 ? "MB" : bytes >= 1024 ? "KB" : "B";
  const divisor = unit === "MB" ? 1024 * 1024 : unit === "KB" ? 1024 : 1;
  const value = new Intl.NumberFormat(language === "bn" ? "bn-BD" : "en-US", { maximumFractionDigits: 1 }).format(bytes / divisor);
  return `${value} ${unit}`;
}
